# !pip install streamlit -q
import streamlit as st
import pickle
import pandas as pd
import numpy as np

with open('rf_model.pkl','rb')as file:
  model=pickle.load(file)
with open('scaler.pkl','rb')as file:
  scaler=pickle.load(file)

df=pd.read_csv('cleaned_real_estate_data.csv')
x_colm=df.drop(columns=['PRICE_IN_LAKHS']).columns

# Design webpage
st.title("Real Estate Price Predictor : Mumbai")
st.write("Enter the property details below:")

# create input boxes for the user
size = st.number_input("Size of Property (sq ft)", value=1000)
bedrooms = st.number_input("Number of Bedrooms", value=2)
floors = st.number_input("Total Floors in Building", value=4)
age = st.number_input("Age of Building (years)", value=5)

# Extract the exact locality names from your dataset columns
locality_list = [col.replace('LOCALITY_', '') for col in x_colm if col.startswith('LOCALITY_')]

# Create a searchable dropdown menu instead of a text box
locality_input = st.selectbox("Locality Name", locality_list)

# predict when button is clicked
if st.button("Predict Price"):
  # create a blank row with all columns set to 0
  input_df=pd.DataFrame(columns=x_colm)
  input_df.loc[0]=0

  # fill the user input
  input_df['SIZE_OF_PROPERTY']=size
  input_df['NO_OF_BEDROOMS']=bedrooms
  input_df['TOTAL_FLOOR']=floors
  input_df['AGE_OF_BUILDING']=age

  # Find the correct Locality column and turn it to 1 (Yes)
  locality_col_name = 'LOCALITY_' + locality_input
  if locality_col_name in input_df.columns:
    input_df[locality_col_name] = 1


  # Ask the scaler exactly what columns and order it remembers
  saved_columns = scaler.feature_names_in_

  # Scale the numbers using that exact saved order
  input_df[saved_columns] = scaler.transform(input_df[saved_columns])

  # model guess the price
  predicted_price=model.predict(input_df)[0]

  # show result in box
  st.success(f"The estimated price is: {predicted_price:.2f} Lakhs")